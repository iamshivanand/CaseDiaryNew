"use client";

import React, { useState } from "react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { ReactQueryDevtools } from "@tanstack/react-query-devtools";

export function QueryProvider({ children }: { children: React.ReactNode }) {
  const [queryClient] = useState(
    () =>
      new QueryClient({
        defaultOptions: {
          queries: {
            staleTime: 1000 * 60 * 5, // 5 minutes: data is considered fresh for 5 mins
            gcTime: 1000 * 60 * 30, // 30 minutes: persist in memory cache
            refetchOnWindowFocus: false, // Prevents unexpected network storms when switching windows
            refetchOnReconnect: true, // Refresh data when internet connection restores
            retry: 1, // Retry once on transient network glitch
          },
          mutations: {
            retry: 0,
          },
        },
      })
  );

  return (
    <QueryClientProvider client={queryClient}>
      {children}
      {process.env.NODE_ENV === "development" && (
        <ReactQueryDevtools initialIsOpen={false} />
      )}
    </QueryClientProvider>
  );
}
